-- Modelo de banco de dados para o sistema de lampada inteligente com ESP32.
-- Dialeto: PostgreSQL.

CREATE TABLE dispositivos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    identificador VARCHAR(100) NOT NULL UNIQUE,
    nome VARCHAR(150) NOT NULL,
    localizacao VARCHAR(200),
    ativo BOOLEAN NOT NULL DEFAULT TRUE,
    criado_em TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE configuracoes (
    dispositivo_id BIGINT PRIMARY KEY
        REFERENCES dispositivos(id) ON DELETE CASCADE,
    limite_ldr INTEGER NOT NULL DEFAULT 2000
        CHECK (limite_ldr BETWEEN 0 AND 4095),
    temperatura_minima NUMERIC(5, 2) NOT NULL DEFAULT 0.00,
    temperatura_maxima NUMERIC(5, 2) NOT NULL DEFAULT 25.00,
    sensor_temperatura_ativo BOOLEAN NOT NULL DEFAULT TRUE,
    detector_ativo BOOLEAN NOT NULL DEFAULT TRUE,
    buzzer_ativo BOOLEAN NOT NULL DEFAULT TRUE,
    painel_ligado BOOLEAN NOT NULL DEFAULT TRUE,
    atualizado_em TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CHECK (temperatura_minima < temperatura_maxima)
);

CREATE TABLE leituras (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dispositivo_id BIGINT NOT NULL
        REFERENCES dispositivos(id) ON DELETE CASCADE,
    temperatura_c NUMERIC(5, 2)
        CHECK (temperatura_c IS NULL OR temperatura_c BETWEEN -24 AND 80),
    luminosidade_adc SMALLINT
        CHECK (luminosidade_adc IS NULL OR luminosidade_adc BETWEEN 0 AND 4095),
    potenciometro_adc SMALLINT
        CHECK (potenciometro_adc IS NULL OR potenciometro_adc BETWEEN 0 AND 4095),
    sistema_ativo BOOLEAN NOT NULL,
    temperatura_sensor_ativo BOOLEAN NOT NULL,
    detector_ativo BOOLEAN NOT NULL,
    buzzer_habilitado BOOLEAN NOT NULL,
    painel_ligado BOOLEAN NOT NULL,
    led_ligado BOOLEAN NOT NULL,
    led_r SMALLINT NOT NULL CHECK (led_r BETWEEN 0 AND 255),
    led_g SMALLINT NOT NULL CHECK (led_g BETWEEN 0 AND 255),
    led_b SMALLINT NOT NULL CHECK (led_b BETWEEN 0 AND 255),
    buzzer_soando BOOLEAN NOT NULL,
    registrada_em TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX leituras_dispositivo_data_idx
    ON leituras (dispositivo_id, registrada_em DESC);

CREATE TABLE comandos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dispositivo_id BIGINT NOT NULL
        REFERENCES dispositivos(id) ON DELETE CASCADE,
    comando VARCHAR(100) NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'recebido'
        CHECK (status IN ('recebido', 'executado', 'rejeitado', 'falhou')),
    resposta TEXT,
    recebido_em TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    processado_em TIMESTAMPTZ
);

CREATE INDEX comandos_dispositivo_data_idx
    ON comandos (dispositivo_id, recebido_em DESC);

CREATE TABLE alertas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dispositivo_id BIGINT NOT NULL
        REFERENCES dispositivos(id) ON DELETE CASCADE,
    leitura_id BIGINT REFERENCES leituras(id) ON DELETE SET NULL,
    tipo VARCHAR(30) NOT NULL
        CHECK (tipo IN ('temperatura_baixa', 'temperatura_alta', 'falha_sensor')),
    descricao TEXT NOT NULL,
    valor NUMERIC(10, 2),
    criado_em TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    resolvido_em TIMESTAMPTZ
);

CREATE INDEX alertas_dispositivo_data_idx
    ON alertas (dispositivo_id, criado_em DESC);

-- A chave anonica do Supabase e publica. Esta politica de exemplo permite
-- somente INSERT de leituras para o dispositivo de ID 1; ajuste junto com
-- DISPOSITIVO_ID no firmware se o ID cadastrado for diferente.
ALTER TABLE leituras ENABLE ROW LEVEL SECURITY;
GRANT INSERT ON TABLE leituras TO anon;
GRANT USAGE ON SEQUENCE public.leituras_id_seq TO anon;

CREATE POLICY esp32_inserir_leituras_dispositivo_1
    ON leituras
    FOR INSERT
    TO anon
    WITH CHECK (dispositivo_id = 1);
